// One InitTypes row: the (assembly slot, namespace, name) triple the
// KnownTypes id resolves to. The member rows reuse this shape for their
// property types.
struct KnownTypeRow {
    std::uint8_t AssemblyIndex; // slot in KnownAssemblies
    const char* Namespace;
    const char* Name;
};

// One InitMembers row: the dependency property on its parent known type
// plus the (assembly slot, namespace, name) triple of its property type.
struct KnownMemberRow {
    KnownTypes Parent;
    const char* Name;
    KnownTypeRow Type;
};

// One InitTypes table row: the id plus its resolved-type triple.
struct KnownTypesEntry {
    KnownTypes Id;
    KnownTypeRow Row;
};

