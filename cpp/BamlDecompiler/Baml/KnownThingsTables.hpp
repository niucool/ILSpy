// Port of ICSharpCode.BamlDecompiler/Baml/KnownThings.g.cs (Ki, 2015, MIT):
// the well-known-things data tables -- the rows the Init* methods seed the
// KnownThings dictionaries with. The ids are the BAML wire-format values
// from KnownTypes/KnownMembers; each row names the framework assembly slot,
// namespace and type name the id resolves to (InitType), the dependency
// property on its parent known type plus its property type (InitMember), the
// two well-known strings, and the SystemColors resource-key table.
//
// This header is the data half only: the KnownThings class that resolves
// these rows through a type system (the IDecompilerTypeSystem /
// SyntheticWpfModule machinery) is a later Phase-9 slice, so the rows stay
// unresolved data -- exactly the Init* call arguments, mechanically
// transcribed.
//
// C#-to-C++ porting decisions:
//  * The C# Dictionary keys become part of each row (the Id / Parent
//    fields), keeping the tables self-describing and the C#'s dictionary
//    insertions reconstructible in one pass; the rows stay in the C#'s
//    insertion order, which is ascending id order.
//  * The KnownMembers range carries the deliberate 137 hole (no member has
//    that value) and the resource ids carry eight holes -- faithfully
//    preserved; a "tidy" resequencing would corrupt the BAML id decode.
//  * The C# Dictionary<int, ...> string/resource keys are short-typed (the
//    C# exposes them as Func<short, ...>), so the rows key on int16_t.
//  * Three member rows name their property type as the generic metadata name
//    "Collection`1" (mscorlib): the real type system's TopLevelTypeName
//    lookup splits the arity off metadata names, so these resolve to null in
//    the shipped engine -- the port's future resolution must reproduce that,
//    not "fix" the rows.
//  * The assembly slots are where the LOOKUP starts, and the shipped engine
//    follows type forwarders from there: on .NET Framework 4.8 fourteen rows
//    resolve through ExportedType forwards (the System.Windows.Markup types
//    from WindowsBase/PresentationFramework into System.Xaml, NameScope into
//    WindowsBase, ICommand from PresentationCore into System). The rows keep
//    the C# slot verbatim; the forwarder walk belongs to the future
//    resolution slice.
//  * `Auto generated. Do not modify.` in the C# and likewise here: the
//    tables were generated mechanically and verified row for row against the
//    SHIPPED ICSharpCode.BamlDecompiler.dll (ilspycmd 11.0.0.9375) -- a real
//    KnownThings constructed over a real BamlDecompilerTypeSystem with the
//    .NET Framework 4.8 WPF assemblies resolved from this machine, its
//    dictionaries dumped via the KnownTablesProbe reflection probe. Every
//    one of the 759 type rows and 267 member rows resolved to a real
//    MetadataTypeDefinition whose assembly, namespace and name match the
//    table triple exactly.

