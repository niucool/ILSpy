// The BamlNode.Parse gold: the crafted Parse-shape .baml streams (the
// omitted-end, unexpected-footer, leaf-first, truncated, two-document,
// empty, and unmatched-footer shapes no real fixture exercises) and the
// block trees the REAL ICSharpCode.BamlDecompiler BamlNode.Parse produces
// over the identical bytes (BamlProbe, out/*.dump.txt). The tree render is
// the probe's DumpTree format: "B <headerType> @<pos> F=@<pos>:<type>" per
// block ("F=@null" while an end record stays omitted), "R <type> @<pos>"
// per record leaf, children indented two spaces.
//
// The truncated fixture's gold shows the C# innermost-return quirk: the
// dump walks from the node Parse RETURNS, and for a truncated document
// that is the innermost open block, not the root.

