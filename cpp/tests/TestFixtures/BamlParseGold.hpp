// t_omit.baml (44 bytes)
inline constexpr char kTOmitBamlHex[] =
    "0c0000004d005300420041004d004c0000006000000060000000600001000000"
    "0000000b0600030000000402";

inline std::string tOmitBamlBytes() {
    std::string bytes;
    bytes.reserve(std::strlen(kTOmitBamlHex) / 2);
    for (const char* p = kTOmitBamlHex; p[0] && p[1]; p += 2) {
        int hi = p[0] <= '9' ? p[0] - '0' : (p[0] | 32) - 'a' + 10;
        int lo = p[1] <= '9' ? p[1] - '0' : (p[1] | 32) - 'a' + 10;
        bytes.push_back(static_cast<char>(hi * 16 + lo));
    }
    return bytes;
}

