// Writes the embedded bytes to a temp file and returns the path
// (MetadataFile needs a real file).
inline std::string WriteResolutionTempFile(const std::string& bytes,
                                           const char* fileName) {
    namespace fs = std::filesystem;
    fs::path path = fs::temp_directory_path() / fileName;
    std::FILE* out = std::fopen(path.string().c_str(), "wb");
    if (out == nullptr) return "";
    std::fwrite(bytes.data(), 1, bytes.size(), out);
    std::fclose(out);
    return path.string();
}
