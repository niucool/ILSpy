// The decoded .resources bytes.
inline std::string TestResourcesBytes() {
    std::string bytes;
    bytes.reserve(std::strlen(kTestResourcesHex) / 2);
    for (const char* p = kTestResourcesHex; p[0] && p[1]; p += 2) {
        int hi = p[0] <= '9' ? p[0] - '0' : (p[0] | 32) - 'a' + 10;
        int lo = p[1] <= '9' ? p[1] - '0' : (p[1] | 32) - 'a' + 10;
        bytes.push_back(static_cast<char>(hi * 16 + lo));
    }
    return bytes;
}

