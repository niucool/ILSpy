// The .resources blob bytes from the manifest (the embedded resource
// named `name`, the row's blob after the 4-byte length prefix).
inline std::optional<std::vector<std::uint8_t>> ValTestResourceData(
    const ILSpy::Decompiler::Metadata::MetadataFile& module,
    const std::string& name) {
    for (const auto& r : module.GetManifestResources()) {
        if (r.Name != name) continue;
        return module.TryGetManifestResourceData(r.Token);
    }
    return std::nullopt;
}

