// The manifest-resource test fixtures the ResourcesFile reader and the
// CLI resource-path suites share (the TinyNetModule.hpp precedent):
//
//  * kTestResourcesHex: a 348-byte .resources container produced by the
//    real System.Resources.ResourceWriter (the .NET 10 runtime's format
//    writer) -- the authoritative ResourceManager V1 header (the
//    "System.Resources.ResourceReader, mscorlib, ..." reader type), a
//    RuntimeResourceSet V2 body with five entries (including the
//    non-ASCII "Unicode.Name." + U+4E2D U+6587 name), and the data
//    section with one value per entry. The .resources name listing and
//    the future value decode pin against it.
//  * kResTestDllHex: a 2 KB assembly manifest built with SRM's
//    MetadataBuilder/ManagedPEBuilder carrying four ManifestResource
//    rows over a managed-resources directory: an embedded valid
//    .resources container (the bytes above), an embedded four-byte
//    .resources-SUFFIXED garbage blob (the parse-failure fallback arm),
//    an embedded three-byte plain resource, and a File-table-linked row
//    (the excluded-from-listing arm) -- every EnumerateResourcePaths
//    shape in one local fixture (no installed assembly carries a
//    .resources-suffixed non-container).
//
// Both were generated with an SDK-10 probe over the installed SRM 10.0.0
// (C:	emp-probe\ResGen\Program.cs); the real ICSharpCode.Decompiler
// ResourcesFile and the real EnumerateResourcePaths logic were driven
// over the same bytes to pin the expectations.

