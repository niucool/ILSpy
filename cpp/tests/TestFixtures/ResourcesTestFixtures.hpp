// Writes the embedded manifest bytes to a temp file and returns the
// path (MetadataFile needs a real file).
inline std::string WriteResTestDll() {
    std::string bytes;
    bytes.reserve(std::strlen(kResTestDllHex) / 2);
    for (const char* p = kResTestDllHex; p[0] && p[1]; p += 2) {
        int hi = p[0] <= '9' ? p[0] - '0' : (p[0] | 32) - 'a' + 10;
        int lo = p[1] <= '9' ? p[1] - '0' : (p[1] | 32) - 'a' + 10;
        bytes.push_back(static_cast<char>(hi * 16 + lo));
    }
    namespace fs = std::filesystem;
    fs::path path = fs::temp_directory_path() / "ilspy_restest_test.dll";
    std::FILE* out = std::fopen(path.string().c_str(), "wb");
    if (out == nullptr) return "";
    std::fwrite(bytes.data(), 1, bytes.size(), out);
    std::fclose(out);
    return path.string();
}

