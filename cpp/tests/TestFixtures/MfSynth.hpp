// Writes the fixture to a temp file (the TinyNetModuleBytes / WriteTinyNetModule
// convention).
inline std::string WriteMfSynthDll(const char* suffix = "")
{
    namespace fs = std::filesystem;
    fs::path path = fs::temp_directory_path()
        / ("ilspy_mfsynth_test" + std::string(suffix) + ".dll");
    std::FILE* out = std::fopen(path.string().c_str(), "wb");
    if (out == nullptr)
        throw std::runtime_error("cannot write MfSynth.dll");
    std::fwrite(kMfSynthBytes, 1, sizeof(kMfSynthBytes), out);
    std::fclose(out);
    return path.string();
}

